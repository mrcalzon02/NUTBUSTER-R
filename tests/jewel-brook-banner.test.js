'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const source=fs.readFileSync(path.join(root,'web/game.js'),'utf8');
const css=fs.readFileSync(path.join(root,'web/style.css'),'utf8');
const activity=fs.readFileSync(path.join(root,'android/app/src/main/java/io/github/mrcalzon02/nutbuster/MainActivity.java'),'utf8');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'web/art/banners/jewel-brook-source.json'),'utf8'));
const bytes=fs.readFileSync(path.join(root,manifest.destinationPath));
const releaseUrl='https://github.com/mrcalzon02/Jewel_Brook/releases';
assert.equal(manifest.publicTitle,'Jewel Brook: Heroes of Embryon');
assert.equal(manifest.releaseUrl,releaseUrl);
assert.equal(manifest.sourceRepository,'mrcalzon02/Jewel_Brook');
assert.equal(bytes.byteLength,115192);
assert.equal(bytes.subarray(0,4).toString(),'RIFF');
assert.equal(bytes.subarray(8,12).toString(),'WEBP');
assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'),manifest.sourceSha256,'Approved source pixels must not change');
assert.equal(crypto.createHash('sha1').update(Buffer.from('blob '+bytes.length+'\0')).update(bytes).digest('hex'),manifest.sourceGitBlobSha,'Cross-repo source Git blob must match exactly');
assert.deepEqual([manifest.width,manifest.height],[939,203]);
const home=source.slice(source.indexOf('function home(){'),source.indexOf('function promoSection('));
assert.match(home,/\$\{jewelBrookPromo\(\)\}/,'Home must use approved cross-promotion slot');
assert.match(source,/function jewelBrookPromo\(\)/);
assert.ok(source.includes('href="'+releaseUrl+'"'),'Banner anchor must reach Jewel Brook releases index');
assert.ok(source.includes('src="art/banners/jewel-brook-banner-wide.webp"'),'Bundled artwork must load offline');
assert.match(source,/target="_blank" rel="noopener noreferrer"/,'Browser fallback is external and isolated');
assert.match(source,/NUTBUSTER_PROMO_BRIDGE\?\.openJewelBrookReleases/,'WebView must use external browser bridge');
assert.match(source,/e\.preventDefault\(\);window\.NUTBUSTER_PROMO_BRIDGE\.openJewelBrookReleases\(\)/,'Bridge must intercept navigation');
assert.ok(activity.includes('Uri.parse("'+releaseUrl+'")'),'Android browser Intent must target verified release page');
assert.match(activity,/@JavascriptInterface public void openJewelBrookReleases\(\)/);
assert.match(activity,/startActivity\(new Intent\(Intent\.ACTION_VIEW/);
assert.ok(activity.includes('"NUTBUSTER_PROMO_BRIDGE"'));
assert.match(css,/\.jewel-brook-banner img\{[^}]*width:100%;height:auto;object-fit:contain/,'Banner must not crop approved art');
assert.match(css,/\.jewel-brook-banner:focus-visible/,'Keyboard focus is visible');
assert.doesNotMatch(home,/rupeeTeaser|rr-banner|rupee-rush-coming-soon|Rupee Rush/i,'Retired promo must stay retired');
assert.match(home,/\$\{homeNews\(\)\}/,'Independent release news must remain');
const parity=JSON.parse(fs.readFileSync(path.join(root,'config/platform-parity.json'),'utf8'));
const review=parity.presentationChangeReviews?.find(x=>x.id==='jewel-brook-approved-crosspromo-2026-10-28');
assert.ok(review,'Explicit four-platform impact audit is required');
assert.deepEqual(Object.keys(review.targetImpact).sort(),['android','fire_os','linux','windows']);
assert.match(review.targetImpact.windows,/does not yet have cross-promotion/,'Do not claim unsupported native desktop feature parity');
console.log('PASS: approved Jewel Brook WebP provenance, offline home render, external GitHub release link, Android/Fire OS bridge, and parity review');
