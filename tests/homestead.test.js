const assert=require('node:assert/strict');
const H=require('../web/homestead.js');
const save={unlocked:500,stars:{1:3,5:2,10:3,25:1,100:2},coins:250,gems:25,boosterInventory:{hammer:3}};
H.ensure(save);
assert.equal(H.DECOR.length,57);assert.equal(H.AVATARS.length,8);assert.equal(H.ACHIEVEMENTS.length,15);
assert.equal(H.stats(save).wins,5,'Unlocked level alone must not count');
assert.equal(H.stats(save).stars,11);
assert.equal(H.owned(save,'acorn'),true);assert.equal(H.owned(save,'final-monument'),false);
assert.equal(H.avatarOwned(save,'baron'),false);
assert.equal(H.place(save,'acorn',0),true);
assert.equal(H.place(save,'acorn',3),true,'Move an owned collectible');
assert.equal(save.homestead.placed[0],undefined,'Decoration cannot duplicate');
assert.equal(H.place(save,'mailbox',3),true,'New item displaces old item to storage');
assert.equal(H.place(save,'final-monument',0),false,'Locked item cannot be placed');
assert.equal(H.place(save,'mailbox',H.TOTAL_PLOTS),false,'No out-of-range placements');
assert.equal(H.place(save,'mailbox',12),true,'Orchard plots unlock from a real level 25 clear');
assert.equal(H.place(save,'mailbox',3),true,'Move between estate zones without duplication');
assert.equal(H.place(save,'constructor',2),false,'Prototype names are not collectibles');
assert.equal(H.remove(save,3),true);assert.equal(H.remove(save,3),false);
assert.equal(H.equip(save,'champion'),true);assert.equal(H.equip(save,'legend'),false);
assert.equal(H.recordWin(save,15,8000),false,'An uncleared level cannot earn score records');
assert.equal(H.recordWin(save,1,8000),true);assert.equal(H.recordWin(save,1,6000),false);
assert.equal(H.recordWin(save,1,13500),true);assert.equal(H.stats(save).bestScore,13500);
assert.equal(H.stats(save).achievements.some(x=>x.id==='score-10k'),true);
assert.equal(H.owned(save,'royal-fountain'),false);
assert.equal(H.purchase(save,'no-such-offer'),false);
assert.equal(H.purchase(save,'royal-estate'),true);
assert.equal(H.purchase(save,'royal-estate'),true,'Idempotent premium claim');
assert.equal(H.equip(save,'royal'),true);assert.equal(H.place(save,'royal-throne',11),true);
const stable=JSON.stringify(save);H.ensure(save);assert.equal(JSON.stringify(save),stable,'Migration must be repeatable');
const old={unlocked:50,stars:{1:1,5:2},hearts:5};
H.ensure(old);assert.equal(H.owned(old,'lantern'),true);assert.equal(old.stars[5],2);
assert.equal(H.stats(old).bestScore,0,'Do not invent historical highs');
const bogus={stars:{},homestead:{avatar:'hacker',placed:{0:'final-monument',1:'mailbox',2:'mailbox',999:'acorn'},purchases:{}}};
H.ensure(bogus);assert.equal(bogus.homestead.avatar,'squire');assert.deepEqual(bogus.homestead.placed,{'1':'mailbox'});
console.log('PASS Homestead: verified ownership, score records, trophy cabinet, placement, migration, avatar cosmetics and royal checkout grant model');
