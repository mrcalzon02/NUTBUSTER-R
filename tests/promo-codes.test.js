'use strict';
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
const Promo=require('../web/promo-codes.js'),P=require('../web/progression.js');
const D=require('../web/daily-moves.js'),B=require('../web/benefits.js');
const t=Date.UTC(2026,9,22,12),cap=24;
const {privateKey,publicKey}=crypto.generateKeyPairSync('ec',{namedCurve:'prime256v1'});
const jwk={...publicKey.export({format:'jwk'}),key_ops:['verify'],ext:true};
const keys={'test-2026':jwk};
const wrap=(payload,key=privateKey)=>{
 const body=Buffer.from(JSON.stringify(payload)).toString('base64url');
 const signing='NBR1.'+body;
 return signing+'.'+crypto.sign('sha256',Buffer.from(signing),{key,dsaEncoding:'ieee-p1363'}).toString('base64url');
};
const make=(grant,nonce='00112233445566778899aabbccddeeff',nbf=0,exp=0)=>({v:1,kid:'test-2026',nonce,nbf,exp,grant});
const context={keys,cryptoImpl:crypto.webcrypto,now:t,at:t,cap,P,D,B};
const save=()=>{const s={unlocked:1,stars:{},coins:0,gems:0,hearts:2,vip:false};P.migrate(s);return s;};
async function run(){
 let s=save(),code=wrap(make({nuts:750,gems:10,moves:5,hearts:2,boosters:{hammer:1,row:2}}));
 assert.equal((await Promo.verify(code,context)).valid,true,'P256 signature must validate with WebCrypto');
 let result=await Promo.redeem(s,code,context);
 assert.equal(result.valid,true);
 assert.equal(s.coins,750);assert.equal(s.gems,10);assert.equal(s.hearts,4);
 assert.equal(D.left(s,t,cap),cap+5);
 assert.equal(P.count(s,'hammer'),6,'Three boosters, including two locked row boosters, substitute into hammer');
 assert.equal(Object.keys(s.promoRedemptions).length,1);
 assert.equal((await Promo.redeem(s,code,context)).reason,'already-redeemed','One redemption per saved ledger');
 let snapshot=JSON.parse(JSON.stringify(s));
 assert.equal((await Promo.redeem(snapshot,code,context)).reason,'already-redeemed','Persistence blocks replay');
 assert.equal((await Promo.verify(code,{...context,keys:{}})).reason,'unknown-issuer');
 assert.equal((await Promo.verify(code,{...context,cryptoImpl:{}})).reason,'crypto-unavailable');
 assert.equal((await Promo.verify('NOTACODE',context)).reason,'invalid-format');
 const parts=code.split('.');
 const tamperedPayload={...make({nuts:99999}),nonce:'00112233445566778899aabbccddeeff'};
 const altered='NBR1.'+Buffer.from(JSON.stringify(tamperedPayload)).toString('base64url')+'.'+parts[2];
 assert.equal((await Promo.verify(altered,context)).reason,'bad-signature','Reward cannot be modified without signing key');
 const corrupted=parts[0]+'.'+parts[1]+'.'+parts[2].replace(/.$/,parts[2].endsWith('A')?'B':'A');
 assert.equal((await Promo.verify(corrupted,context)).valid,false,'Signature tamper must not pay');
 assert.equal((await Promo.verify(wrap(make({nuts:1},'a'.repeat(32),t+1000,t+2000)),context)).reason,'not-yet-valid');
 assert.equal((await Promo.verify(wrap(make({nuts:1},'b'.repeat(32),0,t)),context)).reason,'expired');
 assert.equal(Promo.validate(make({gems:10001})),false,'Reject huge unsupported rewards');
 assert.equal(Promo.validate(make({boosters:{superboss:1}})),false,'Reject unknown boost keys');
 assert.equal(Promo.validate(make({vip:true})),true);
 const onlyVip=wrap(make({vip:true},'c'.repeat(32)));
 s=save();result=await Promo.redeem(s,onlyVip,context);
 assert.equal(result.valid,true);assert.equal(s.vip,true);
 assert.equal(s.coins,250,'VIP immediately adds its daily +250 nuts');
 assert.equal(D.left(s,t,cap),cap+5,'VIP adds five baseline daily moves');
 assert.equal(P.count(s,'hammer'),7,'VIP adds four starter substituted boosters');
 assert.equal((await Promo.redeem(s,onlyVip,context)).reason,'already-redeemed');
 assert.equal((await Promo.redeem(save(),onlyVip,context)).valid,true,'Limitation: a separate offline save can redeem the same signed code');
 assert.equal((await Promo.redeem(s,wrap(make({vip:true},'d'.repeat(32))),context)).reason,'already-owned');
 const noClaim=await Promo.redeem(s,wrap(make({hearts:1},'e'.repeat(32))),context);
 assert.equal(noClaim.valid,true,'Hearts below max remain useful');
 assert.equal(s.hearts,3);
 s.hearts=5;
 assert.equal((await Promo.redeem(s,wrap(make({hearts:1},'f'.repeat(32))),context)).reason,'hearts-full');
 assert.equal(Promo.ledger(s)['f'.repeat(32)],undefined,'Do not consume worthless full-heart voucher');
 console.log('PASS: real P-256 signing/WebCrypto verification, tamper refusal, constrained gifts, 24h VIP credit, save ledger replay protection and offline limitation');
}
run().catch(e=>{console.error(e);process.exitCode=1});
