const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const H=require('../web/homestead.js');
const tiers=H.HOUSE_TIERS;
assert.equal(tiers.length,40,'40 genuinely distinct house designs');
assert.equal(new Set(tiers.map(x=>x.name)).size,40);
assert.equal(tiers[0].tier,1);assert.equal(tiers[0].level,0);
assert.equal(tiers[2].level,25);assert.equal(tiers[8].level,100);
assert.equal(tiers[20].level,250);assert.equal(tiers[32].level,400);
assert.equal(tiers[39].level,500);
for(let i=0;i<40;i++){
 const entry=tiers[i];
 assert.equal(entry.tier,i+1,'Tier identity must match progression order');
 assert.ok(i===0||entry.level>tiers[i-1].level,'Campaign unlock gates must strictly rise');
}
const fresh={unlocked:500,coins:1000,stars:{}};
H.ensure(fresh);
assert.equal(fresh.homestead.maxTier,1);
assert.equal(fresh.homestead.tier,1);
assert.equal(H.chooseTier(fresh,2),false,'Unbought design not equipable');
assert.equal(H.upgradeTier(fresh).reason,'level','unlocked campaign marker is not victory');
fresh.stars[tiers[1].level]=1;fresh.coins=tiers[1].cost-1;
const denied=H.upgradeTier(fresh);
assert.equal(denied.reason,'coins');
assert.equal(fresh.coins,tiers[1].cost-1);
assert.equal(fresh.homestead.maxTier,1);
fresh.coins=100000;
const first=H.upgradeTier(fresh);
assert.equal(first.valid,true);
assert.equal(first.tier,2);
assert.equal(first.spent,tiers[1].cost);
const post=fresh.coins;
assert.equal(H.chooseTier(fresh,1),true);
assert.equal(fresh.coins,post,'Re-selecting existing design never costs money');
assert.equal(H.chooseTier(fresh,2),true);
assert.equal(H.chooseTier(fresh,3),false);
assert.equal(H.upgradeTier(fresh).reason,'level','cannot skip any tier');
fresh.stars[tiers[2].level]=1;
assert.equal(H.upgradeTier(fresh).tier,3);
assert.equal(H.chooseTier(fresh,2),true);
const stable=JSON.stringify(fresh);H.ensure(fresh);
assert.equal(JSON.stringify(fresh),stable);
const legacy={stars:{25:2,100:1,250:1,400:1},coins:1234,homestead:{houses:{cottage:true,lodge:true,manor:true,estate:true,palace:true},house:'manor'}};
H.ensure(legacy);
assert.equal(legacy.homestead.maxTier,33,'Original palace ownership maps to tier 33');
assert.equal(legacy.homestead.tier,9,'Previously displayed manor is honored');
assert.equal(legacy.coins,1234,'Migration must not charge or reduce funds');
assert.equal(H.chooseTier(legacy,34),false);
const previous=JSON.stringify(legacy);H.ensure(legacy);
assert.equal(JSON.stringify(legacy),previous);
const endgame={stars:{},coins:100000,homestead:{houses:{cottage:true,palace:true},house:'palace'}};
for(const t of tiers.slice(33))endgame.stars[t.level]=3;
endgame.stars[400]=3;
H.ensure(endgame);
assert.equal(endgame.homestead.maxTier,33);
let cost=0;
for(let tier=34;tier<=40;tier++){
 const next=H.upgradeTier(endgame);
 assert.equal(next.valid,true,'Build tier '+tier);
 assert.equal(next.tier,tier);
 cost+=tiers[tier-1].cost;
}
assert.equal(endgame.homestead.maxTier,40);
assert.equal(H.upgradeTier(endgame).reason,'complete');
assert.equal(endgame.coins,100000-cost);
assert.match(H.prestigePlate(endgame),/Tier 40\/40/);
assert.match(H.prestigePlate(endgame),/Eternal Nut Imperium/);
assert.equal(H.chooseTier(endgame,1),true,'Can display humble beginnings after finishing');
assert.equal(H.chooseTier(endgame,41),false);
console.log('PASS: 40 house progression tiers, level gates, migration, costs and unlocks');
