'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const source=fs.readFileSync(path.join(root,'web/game.js'),'utf8');
const css=fs.readFileSync(path.join(root,'web/style.css'),'utf8');
const start=source.indexOf('function home(){');
const end=source.indexOf('function promoSection(',start);
assert.ok(start>=0&&end>start,'Home screen must remain present');
const home=source.slice(start,end);
assert.doesNotMatch(source,/function rupeeTeaser\(/,'Retired Rupee Rush teaser must not be rendered');
assert.doesNotMatch(home,/rupeeTeaser|rr-banner|rupee-rush-coming-soon|Rupee Rush/i,'No retired game promotion on home');
assert.doesNotMatch(css,/\.rr-banner\b/,'Retired banner styles must not reserve space');
assert.ok(home.includes('homeNews()'),'Retain the independent release-news ticker');
assert.ok(home.includes('homeTitleCard()'),'Retain Nut Buster title and navigation');
assert.match(home,/data-nav="wharf"/,'Retain established navigation');
const art=path.join(root,'web/art/banners/rupee-rush-coming-soon.png');
assert.ok(fs.existsSync(art),'Preserve original illustration for separate approved rebrand');
console.log('PASS: home removes retired Rupee Rush advertisement, preserves news/navigation/art');
