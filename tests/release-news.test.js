const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const moduleUnderTest=require('../tools/release-news.js');
const ROOT=path.resolve(__dirname,'..');
const doc=JSON.parse(fs.readFileSync(path.join(ROOT,'release/changelog.json'),'utf8'));
const covered=moduleUnderTest.validate(doc);
for(const changed of doc.changes)assert.ok(changed.files.some(file=>covered.has(file)));
assert.throws(()=>moduleUnderTest.validate({...doc,changes:[]}),/real change entries/);
const bounded={title:'Strict note text length validation',detail:'x'.repeat(300),files:['tools/planning-policy.js']};
assert.doesNotThrow(()=>moduleUnderTest.validate({...doc,changes:[bounded]}),'300-character details remain legal');
assert.throws(()=>moduleUnderTest.validate({...doc,changes:[{...bounded,detail:'x'.repeat(301)}]}),/needs a specific title and meaningful detail/,'301-character details must fail');
assert.throws(()=>moduleUnderTest.validate({...doc,changes:[{...bounded,title:'x'.repeat(101)}]}),/needs a specific title and meaningful detail/,'Overlong titles must fail');

assert.throws(()=>moduleUnderTest.validate({...doc,changes:[{title:'A mystery',detail:'Various fixes and improvements that are not specific.',files:['web/game.js']}]}),/placeholder/);
assert.throws(()=>moduleUnderTest.validate({...doc,changes:[{title:'Fictional feature',detail:'We added a feature from a file that is not actually present in this repository.',files:['web/no-such-feature.js']}]}),/does not exist/);
assert.throws(()=>moduleUnderTest.validate({...doc,changes:[{title:'Unsafe path',detail:'This item is an unsafe release file path that must not be included.',files:['../outside.js']}]}),/unsafe/);
const news=moduleUnderTest.buildNews(doc,'nutbuster-phone-test-999-1','a'.repeat(40),'2026-10-23');
assert.equal(news.changes.length,doc.changes.length);
assert.ok(!JSON.stringify(news).includes('"files"'),'paths are validation evidence, not player-facing text');
const notes=moduleUnderTest.releaseNotes(news,'214900000','b'.repeat(64));
assert.match(notes,/Source revision: a{40}/);assert.match(notes,/NUTBUSTER publisher signer SHA-256: b{64}/);
for(const entry of doc.changes){assert.ok(notes.includes(entry.title));assert.ok(notes.includes(entry.detail));}
assert.throws(()=>moduleUnderTest.buildNews(doc,'bad-tag','a'.repeat(40),'2026-10-23'),/invalid publication tag/);
const shell=fs.readFileSync(path.join(ROOT,'web/index.html'),'utf8');
assert.match(shell,/src="release-news\.js"/);assert.match(shell,/src="game\.js"/);
assert.ok(shell.indexOf('release-news.js')<shell.indexOf('game.js'),'news must load before home render');
const source=fs.readFileSync(path.join(ROOT,'web/game.js'),'utf8');
assert.match(source,/NutbusterReleaseNews/);
assert.match(source,/release-news-ticker/);
const preview={};vm.runInNewContext(fs.readFileSync(path.join(ROOT,'web/release-news.js'),'utf8'),{window:preview});
assert.equal(preview.NutbusterReleaseNews.tag,null,'source preview cannot claim unpublished news');
const wf=fs.readFileSync(path.join(ROOT,'.github/workflows/build-and-release.yml'),'utf8');
assert.match(wf,/NUTBUSTER_RELEASE_BASE/);
assert.match(wf,/node tools\/release-news\.js --check/);
assert.match(wf,/node tools\/release-news\.js --generate/);
assert.match(wf,/node tools\/release-news\.js --notes/);
assert.match(wf,/NUTBUSTER-news\.json/);
console.log('PASS: actual-change release notes, validation, packaging, and home news contract');
