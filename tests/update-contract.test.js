'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const gradle=read('android/app/build.gradle');
const manifest=read('android/app/src/main/AndroidManifest.xml');
const main=read('android/app/src/main/java/io/github/mrcalzon02/nutbuster/MainActivity.java');
const workflow=read('.github/workflows/build-and-release.yml');
const update=read('web/update.js');
const pinned=read('config/nutbuster-publisher.sha256').trim();
assert.equal(pinned,'cdde49a6d72b49e50d1cf3454ebb0a1e63444640719e4afa40c6c74bd5c8b0b9','existing publisher signing identity is unchanged');
assert.match(gradle,/assets\.srcDirs = \['\.\.\/\.\.\/web'\]/);
assert.match(gradle,/minSdk 26/);
assert.match(gradle,/targetSdk 36/);
assert.match(gradle,/validatePublisherSigning/);
assert.match(gradle,/signerHash != pinnedSigner/);
assert.ok(gradle.includes('!haveSigning || signerHash != pinnedSigner'),'publisher signer validation unchanged');
assert.doesNotMatch(manifest,/REQUEST_INSTALL_PACKAGES|android\.permission\.INTERNET|FileProvider|grantUriPermissions/,'no dangerous install or network capability in APK manifest');
assert.doesNotMatch(gradle,/androidx\.core:core/,'unused installer support library must be absent');
assert.ok(!fs.existsSync(path.join(root,'android/app/src/main/java/io/github/mrcalzon02/nutbuster/NutUpdateService.java')),'native downloader and installer code must be removed');
assert.ok(!fs.existsSync(path.join(root,'android/app/src/play/AndroidManifest.xml')),'obsolete installer-permission overlay must be removed');
assert.ok(!fs.existsSync(path.join(root,'android/app/src/main/res/xml/update_paths.xml')),'installer FileProvider paths removed');
assert.match(main,/s\.setBlockNetworkLoads\(true\)/);
assert.match(main,/shouldOverrideUrlLoading\(WebView view, WebResourceRequest request\)/);
assert.match(main,/setAllowUniversalAccessFromFileURLs\(false\)/);
assert.match(main,/NUTBUSTER_UPDATE_BRIDGE/);
assert.match(main,/openReleases\(\)/);
assert.doesNotMatch(main,/NutUpdateService|checkForUpdatesAutomatically\(\)|checkForUpdates\(\)|ACTION_MANAGE_UNKNOWN_APP_SOURCES|ACTION_INSTALL_PACKAGE/);
assert.doesNotMatch(update,/autoCheck\(|checkForUpdatesAutomatically|checkForUpdates\(/);
assert.match(update,/https:\/\/github\.com\/mrcalzon02\/NUTBUSTER-R\/releases/);
assert.match(workflow,/PHONE_TEST_KEYSTORE_BASE64/);
assert.match(workflow,/NUTBUSTER signing secrets missing/);
assert.match(workflow,/Wrong signing certificate: only the NUTBUSTER-owned publisher key is permitted/);
assert.match(workflow,/gh release create "\$TAG" --draft/);
assert.match(workflow,/remote SHA-256\/size readback mismatch/);
assert.match(workflow,/--draft=false/);
assert.doesNotMatch(workflow,/generate_update_manifest\.py|NUTBUSTER-update\.json/,'no legacy self-updater metadata');
const setup=read('scripts/setup-nutbuster-signing.sh');
assert.doesNotMatch(setup,/keytool -genkeypair|openssl rand/);
assert.match(setup,/No secrets were changed/);
assert.match(read('web/index.html'),/src="update.js"/);
require('./update-and-invite.test.js');
console.log('PASS: signed GitHub APK channel, external browser update link, no in-app installer/auto-check');
