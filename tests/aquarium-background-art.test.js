'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const F=require('../web/fishing.js'),U=require('../web/fishing-ui.js');
const prefix='art/aquarium/backgrounds/v1/',directory=path.join(__dirname,'../web/art/aquarium/backgrounds/v1');
const manifest=JSON.parse(fs.readFileSync(path.join(directory,'manifest.json'),'utf8'));
const csv=fs.readFileSync(path.join(__dirname,'../docs/contracts/nutbuster-primary-mechanics-and-asset-lock.csv'),'utf8');
assert.equal(manifest.scenes.length,6,'Six approved plain-water scenes should be installed');
assert.equal(F.BACKGROUNDS.length,11,'Do not remove the original five aquarium themes');
const oldIds=['lagoon','river','reef','deep','arcane'];
for(const id of oldIds)assert.ok(F.BACKGROUNDS.some(b=>b.id===id),'Prior scene lost: '+id);
const sceneIds=new Set;
for(const scene of manifest.scenes){
 assert.ok(!sceneIds.has(scene.id),'Duplicate backdrop '+scene.id);
 sceneIds.add(scene.id);
 const spec=F.BACKGROUNDS.find(b=>b.id===scene.id);
 assert.ok(spec,'Aquarium engine has no '+scene.id);
 assert.equal(spec.art,scene.path.replace(/^web\//,''));
 assert.deepEqual([...spec.need],[...scene.need],'Discovery gate disagrees with art manifest');
 const filename=path.join(__dirname,'../',scene.path);
 const bytes=fs.readFileSync(filename);
 assert.equal(bytes.subarray(0,8).toString('hex'),'89504e470d0a1a0a','Must be original PNG data');
 assert.equal(bytes.readUInt32BE(16),1672,'Do not crop approved landscape '+scene.id);
 assert.equal(bytes.readUInt32BE(20),941,'Do not crop approved landscape '+scene.id);
 const sha=crypto.createHash('sha1').update('blob '+bytes.length+'\0').update(bytes).digest('hex');
 assert.equal(sha,scene.sha,'Artwork file is not the approved source '+scene.id);
 assert.ok(csv.includes(sha)&&csv.includes(scene.path),'Art identity must be protected in mechanics contract');
}
const now=new Date(2030,7,15).getTime();
const save={coins:141,gems:9,nutravaganza:{dollars:450,fish:[{id:'minnow',size:42,value:15},{id:'bluegill',size:50,value:24}]}};
let n=F.ensure(save,now);
assert.equal(n.aquarium.background,'plain-seafloor','New tanks should use the approved empty stage by default');
assert.ok(F.backgroundUnlocked(n,'plain-seafloor')&&F.backgroundUnlocked(n,'plain-kelp-lagoon'),'Open scenes available from first tank');
assert.ok(F.backgroundUnlocked(n,'plain-kelp-canyon'),'Bluegill discovery opens canyon');
assert.equal(F.backgroundUnlocked(n,'plain-coral'),false,'Do not pre-unlock rare reef scenery');
assert.equal(F.chooseBackground(save,'plain-coral',now).valid,false,'Cannot bypass catch requirement');
const beforeFish=JSON.stringify(n.fish);
const ok=F.placeStamp(save,'coral',42,47,now);
assert.equal(ok.valid,true,'Caught minnow should unlock its coral stamp');
const placed=JSON.stringify(n.aquarium.stamps);
let rendered=U.aquarium(save);
assert.ok(rendered.includes('aquarium-swimmer'));
assert.equal(F.chooseBackground(save,'plain-seafloor',now).valid,true);
rendered=U.aquarium(save);
assert.ok(rendered.includes('aquarium-real-backdrop'),'Rendered glass must use the selected art');
assert.ok(rendered.includes(prefix+'plain-seafloor.png'),'Rendered glass must reference real asset');
assert.ok(!rendered.includes('🪨 🌿 🪸 🐚 🌾 🪸 🌿'),'No emoji floor baked over scenery');
const editor=U.aquarium(save,{aquariumEditing:true,aquariumStamp:null,aquariumFishFrom:null});
assert.equal((editor.match(/class="aquarium-theme /g)||[]).length,11,'All themes exposed in compact editor');
assert.ok(editor.includes('src="'+prefix+'plain-kelp-canyon.png"'),'Source images are visible in picker');
assert.ok(editor.includes('src="'+prefix+'plain-seafloor.png"'),'Open backgrounds have previews');
assert.ok(editor.includes('data-background="plain-coral" disabled'),'Locked coral theme cannot be selected');
n.aquarium.discovered.push('koi','trout','perch');
for(const scene of manifest.scenes){
 assert.equal(F.backgroundUnlocked(n,scene.id),true,'Seeded species must unlock all scenes: '+scene.id);
 assert.equal(F.chooseBackground(save,scene.id,now).valid,true);
 const view=U.aquarium(save);
 assert.ok(view.includes('background-image:url('+scene.path.replace(/^web\//,'')+')'),'Scene must be in tank background layer '+scene.id);
 assert.equal(JSON.stringify(n.fish),beforeFish,'Theme switching must not move or delete fish');
 assert.equal(JSON.stringify(n.aquarium.stamps),placed,'Theme switching must not move or delete user stamps');
}
const copy=JSON.parse(JSON.stringify(save)),restored=F.ensure(copy,now);
assert.equal(restored.aquarium.background,manifest.scenes.at(-1).id,'Last choice persists after reload');
assert.equal(JSON.stringify(restored.aquarium.stamps),placed);
assert.equal(copy.coins,141);assert.equal(copy.gems,9);assert.equal(restored.dollars,450);
const css=fs.readFileSync(path.join(__dirname,'../web/fishing.css'),'utf8');
assert.ok(css.includes('background-size:100% 100%'),'Glass must show the entire image instead of cropping');
assert.ok(css.includes('.aquarium-art-scene .aquarium-floor'),'Art-backed scene must not draw prefab decorations over user stamps');
console.log('PASS six verified scenic PNGs, eleven choices, catch gates, no-crop water layer, retained fish/stamps and save/reload');
