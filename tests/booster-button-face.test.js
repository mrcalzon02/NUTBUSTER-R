// The artwork itself must be the visible booster button, while the original
// six-column/two-row grid, hit rectangles, and gameplay event hooks stay intact.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const css=read('web/style.css');
const game=read('web/game.js');
const marker='/* Artwork-faced tactical buttons:';
const offset=css.indexOf(marker);
assert.ok(offset!==-1,'booster face layout override must be installed');
const patch=css.slice(offset);
const rule=selector=>{
 const start=patch.indexOf(selector+'{');
 assert.notEqual(start,-1,'missing booster rule '+selector);
 return patch.slice(start+selector.length+1).split('}')[0];
};
const base='#app.playing .game-active .boosters';
assert.match(css,/grid-template-columns:repeat\(6,minmax\(0,1fr\)\)/,'all 12 controls remain on two six-column rows');
assert.match(css,/\.boosters button\{width:100%;height:51px;min-width:0;min-height:51px/,'51px hit boxes preserved');
assert.match(css,/\.boosters button\{height:46px;min-height:46px/,'short-portrait hit boxes preserved');
const face=rule(base+' button');
assert.match(face,/background:transparent/,'remove the painted shell');
assert.match(face,/border:0/,'remove the outer border');
assert.match(face,/padding:0/,'eliminate inset icon framing');
assert.doesNotMatch(face,/(?:^|;)\s*(?:height|width|min-height|min-width|grid-template-columns)\s*:/,'the face patch cannot resize controls');
const wrap=rule(base+' .booster-picture');
assert.match(wrap,/position:absolute/);
assert.match(wrap,/width:100%/,'artwork occupies the full horizontal button face');
const power=rule(base+' .booster-icon');
assert.match(power,/width:100%/);
assert.match(power,/height:100%/);
assert.match(power,/object-fit:contain/,"never crop the owner's icons");
assert.match(power,/border:0/,'no nested icon frames');
const hold=rule(base+' .hold-icon');
assert.match(hold,/width:100%/,'gravity-hold art grows with normal power art');
assert.match(hold,/object-fit:contain/);
const label=rule(base+' .booster-label');
assert.match(label,/position:absolute/);
assert.match(label,/font-size:10px!important/,'readable labels overlay the art');
const stock=rule(base+' button [data-stock]');
assert.match(stock,/position:absolute/);
assert.match(stock,/z-index:3/,'stock/lock badge is above the button art');
assert.match(stock,/pointer-events:none/,'stock badge cannot steal touch input');
assert.match(game,/data-tool=/,'boosters remain clickable');
assert.match(game,/data-hold-tool=/,'gravity holds remain clickable');
assert.match(game,/data-stock/,'inventory/level badge updates remain connected');
assert.match(game,/const BOOSTER_ART=P\.BOOSTER_ART;/,'use the original authored artwork');
console.log('PASS: full-art booster faces, overlaid badges, unchanged two-row hit areas and hooks');
