const assert=require('node:assert/strict');
const H=require('../web/homestead.js');
const fresh={unlocked:500,stars:{1:2},coins:250,gems:25};
H.ensure(fresh);
assert.equal(H.SLOTS,12,'Original yard capacity stable');
assert.equal(H.TOTAL_PLOTS,44);
assert.deepEqual(H.ZONES.map(z=>z.level),[0,25,100,250,400]);
assert.deepEqual(H.ZONES.map(z=>z.start),[0,12,20,28,36]);
assert.equal(H.DECOR.length,57);assert.equal(H.HOUSES.length,5);
assert.equal(H.PETS.length,8);assert.equal(H.SETS.length,5);
assert.equal(H.zoneUnlocked(fresh,'orchard'),false,'Unlocked campaign markers are not proof of victory');
assert.equal(H.zoneForSlot(0).id,'yard');
assert.equal(H.zoneForSlot(12).id,'orchard');
assert.equal(H.zoneForSlot(20).id,'terrace');
assert.equal(H.zoneForSlot(28).id,'lake');
assert.equal(H.zoneForSlot(36).id,'palace');
assert.equal(H.zoneForSlot(44),null);
assert.equal(H.place(fresh,'mailbox',12),false,'Locked orchard not writable');
assert.equal(H.place(fresh,'mailbox',0),true);
assert.equal(H.petOwned(fresh,'owl'),false);
assert.equal(H.equipPet(fresh,'owl'),false);
assert.equal(H.buildHouse(fresh,'lodge').reason,'level');
assert.equal(H.stats(fresh).zones,1);
const first=H.prestigePlate(fresh);
assert.match(first,/NUTVALE HOMESTEAD/);
assert.match(first,/1\/500 levels/);
assert.doesNotMatch(first,/undefined|NaN/);
fresh.stars[3]=3;
assert.equal(H.owned(fresh,'homely-sign'),true,'Collection completion unlocks reward');
assert.equal(H.setProgress(fresh)[0].complete,true);
assert.equal(H.stats(fresh).setCount,1);
assert.equal(H.owned(fresh,'society-plaque'),false);
assert.equal(H.place(fresh,'homely-sign',3),true);
fresh.stars[25]=2;
assert.equal(H.zoneUnlocked(fresh,'orchard'),true);
assert.equal(H.place(fresh,'mailbox',12),true);
assert.equal(fresh.homestead.placed[0],undefined,'Single instance across zone bounds');
assert.equal(H.buildHouse(fresh,'lodge').reason,'coins','Construction requires Golden Nuts');
fresh.coins=2150;
const built=H.buildHouse(fresh,'lodge');
assert.equal(built.valid,true);assert.equal(built.spent,2000);
assert.equal(fresh.coins,150);
const again=H.buildHouse(fresh,'lodge');
assert.equal(again.valid,true);assert.equal(again.spent,0);
assert.equal(fresh.coins,150,'Re-selecting purchased home cannot charge twice');
assert.equal(fresh.homestead.house,'lodge');
assert.equal(H.equipPet(fresh,'owl'),true);
assert.equal(H.equipPet(fresh,'dragon'),false);
assert.equal(H.owned(fresh,'world-tree'),false);
for(const level of [100,250,400,500])fresh.stars[level]=1;
assert.equal(H.stats(fresh).zones,5);
assert.equal(H.place(fresh,'mailbox',43),true);
assert.equal(H.place(fresh,'mailbox',44),false);
assert.equal(H.place(fresh,'mailbox',-1),false);
assert.equal(H.place(fresh,'mailbox',1.5),false);
assert.equal(H.remove(fresh,43),true);
assert.equal(H.remove(fresh,43),false);
const old={stars:{1:1,3:1,25:1,100:1},unlocked:450,coins:5000,
 homestead:{placed:{0:'mailbox',1:'mailbox',11:'acorn',12:'sapling',13:'final-monument',20:'flowerbed',28:'gold-statue',99:'acorn'},houses:{cottage:true,lodge:true,manor:true,palace:true},house:'palace',pet:'hacker',avatar:'constructor'}};
H.ensure(old);
assert.equal(old.homestead.placed[0],'mailbox');
assert.equal(old.homestead.placed[1],undefined,'Duplicate from legacy save removed');
assert.equal(old.homestead.placed[12],'sapling','Earned extra-ground placement preserved');
assert.equal(old.homestead.placed[13],undefined,'Locked item cannot be inserted via save');
assert.equal(old.homestead.placed[20],'flowerbed');
assert.equal(old.homestead.placed[28],undefined,'Locked zone pruned');
assert.equal(old.homestead.houses.manor,true,'Valid built houses retained');
assert.equal(old.homestead.houses.palace,undefined);
assert.equal(old.homestead.house,'cottage','Illegal house state normalized');
assert.equal(old.homestead.pet,'squirrel');
assert.equal(old.homestead.avatar,'squire');
const stable=JSON.stringify(old);
H.ensure(old);assert.equal(JSON.stringify(old),stable,'Repeat migrations do not alter state');
assert.equal(old.coins,5000,'Migration never changes existing wallet');
assert.equal(old.stars[100],1,'Migration never changes campaign completion');
assert.equal(H.buildHouse(old,'constructor').valid,false,'Prototype keys cannot select arbitrary house');
assert.equal(H.equipPet(old,'constructor'),false);
const max={stars:{},coins:100000};for(let i=1;i<=500;i++)max.stars[i]=3;
H.ensure(max);
assert.equal(H.stats(max).setCount,5);
assert.equal(H.owned(max,'world-tree'),true);
assert.equal(H.stats(max).zones,5);
assert.equal(H.stats(max).achievements.some(a=>a.id==='all-sets'),true);
assert.equal(H.stats(max).achievements.some(a=>a.id==='full-estate'),true);
assert.equal(H.buildHouse(max,'palace').spent,50000);
assert.equal(max.coins,50000);
assert.equal(H.prestigePlate(max).includes('Tier 33/40'),true,'The original palace maps to the 33rd of 40 visual tiers');
console.log('PASS Homestead expansion: 5 gated grounds, 44 plots, 5 houses, 8 pets, 5 earned sets, safe migration and deterministic prestige plate');
