'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const F=require('../web/fishing.js'),U=require('../web/fishing-ui.js');
const day=Date.UTC(2031,3,4,13);
const fish=F.FISH;
assert.equal(fish.length,80);
assert.equal(new Set(fish.map(x=>x.id)).size,fish.length);
assert.ok(fish.slice(0,12).every(spec=>spec.name.endsWith(' Fry')),'Original twelve species must be labeled as fry');
assert.ok(fish.slice(12).every(spec=>!spec.name.endsWith(' Fry')),'Only the original twelve species are fry');
assert.equal(new Set(fish.map(x=>x.maxSize)).size,fish.length,'Each species must have a different maximum length');
for(const spec of fish){
 assert.ok(Number.isInteger(spec.maxSize)&&spec.maxSize>=1,'Invalid max '+spec.id);
 for(const seed of [0,1,512,428334991,4294967295]){
  const value=F.generatedSize(spec,seed);
  assert.ok(Number.isInteger(value)&&value>=1&&value<=spec.maxSize,'Generated length outside bound: '+spec.id);
  assert.equal(F.generatedSize(spec,seed),value,'Seed must reproduce the same fish length');
 }
}
const minnow=fish.find(x=>x.id==='minnow'),leviathan=fish.find(x=>x.id==='leviathan');
assert.ok(leviathan.maxSize>minnow.maxSize*10);
const lengthCsv=fs.readFileSync(path.join(__dirname,'../docs/economy/fish-size-records.csv'),'utf8');
assert.equal(lengthCsv.trim().split(/\r?\n/).length,fish.length+1);
for(const spec of fish)assert.ok(lengthCsv.includes('"'+spec.id+'","'+spec.name+'","'+spec.maxSize+'"'),spec.id+' length contract missing');
const save={coins:1250,gems:66,nutravaganza:{day:'2031-04-04',dollars:0,fish:[]}},n=F.ensure(save,day);
const lengths=Array.from({length:1000},(_,seed)=>({seed,size:F.generatedSize(minnow,seed)})).sort((a,b)=>a.size-b.size);
assert.ok(lengths.at(-1).size>lengths[0].size);
function catchFish(spec,seed){
 n.fight={id:spec.id,seed,rodId:'woodland',turn:0,fish:50,hook:50,progress:99,tension:0};
 const caught=F.step(save,'reel',day);
 assert.equal(caught.status,'caught');
 assert.equal(caught.catch.size,F.generatedSize(spec,seed));
 assert.ok(caught.catch.size<=spec.maxSize);
 return caught;
}
const first=catchFish(minnow,lengths[0].seed);
assert.equal(first.trophy.newSpecies,true);
assert.equal(first.trophy.newRecord,true);
assert.equal(first.trophy.previous,0);
assert.equal(n.trophyRecords.minnow.size,lengths[0].size);
assert.equal(F.trophyStatus(save,day).collected,1);
assert.equal(F.resolve(save,'sell',day).valid,true);
assert.equal(n.trophyRecords.minnow.size,lengths[0].size,'Selling retains the mount');
const repeat=catchFish(minnow,lengths[0].seed);
assert.equal(repeat.trophy.newRecord,false);
assert.equal(repeat.trophy.catches,2);
assert.equal(F.resolve(save,'release',day).valid,true);
const bigger=catchFish(minnow,lengths.at(-1).seed);
assert.equal(bigger.trophy.newSpecies,false);
assert.equal(bigger.trophy.newRecord,true);
assert.equal(bigger.trophy.previous,lengths[0].size);
assert.equal(n.trophyRecords.minnow.size,lengths.at(-1).size);
assert.equal(n.trophyRecords.minnow.catches,3);
assert.equal(F.resolve(save,'keep',day).valid,true);
assert.equal(n.fish.length,1);
const recorded=catchFish(leviathan,512);
assert.ok(recorded.catch.size>100,'Large catch regression must exercise former 100 cm validator');
assert.equal(F.ensure(save,day).pending.size,recorded.catch.size,'Validator must not delete a large pending fish');
assert.equal(F.resolve(save,'release',day).valid,true);
assert.equal(n.trophyRecords.leviathan.size,recorded.catch.size,'Releasing retains a huge record');
assert.equal(F.trophyStatus(save,day).collected,2);
assert.equal(F.trophyStatus(save,day).totalCatches,4);
assert.equal(save.coins,1250);
assert.equal(save.gems,66);
const hall=U.trophyHall(save),preview=U.trophyPreview(save);
assert.match(hall,/Penny Minnow/);
assert.match(hall,/Nutvale Leviathan/);
assert.match(hall,new RegExp(String(recorded.catch.size)+' cm'));
assert.match(hall,/3 caught/);
assert.equal((hall.match(/class="fish-trophy-mount /g)||[]).length,80);
assert.equal((hall.match(/class="fish-trophy-mount earned"/g)||[]).length,2);
assert.ok(!hall.includes('Constellation Gar'),'Uncaught fish art/names should not leak');
assert.match(preview,/VIEW RECORD WALL/);
assert.match(preview,/Penny Minnow/);
const copy=JSON.parse(JSON.stringify(save)),restored=F.ensure(copy,day);
assert.equal(restored.trophyRecords.leviathan.size,recorded.catch.size);
assert.equal(restored.trophyRecords.minnow.catches,3);
assert.equal(copy.nutravaganza.fish.length,1);
const prevCount=restored.trophyRecords.minnow.catches;
F.trophyStatus(copy,day);U.trophyHall(copy);
assert.equal(restored.trophyRecords.minnow.catches,prevCount,'Viewing a record cannot duplicate catches');
const legacy={nutravaganza:{day:'2031-04-04',fish:[{id:'minnow',size:30,value:20}]}};
F.ensure(legacy,day);
assert.equal(F.trophyStatus(legacy,day).collected,1,'Aquarium specimens migrate to initial records');
assert.equal(legacy.nutravaganza.trophyRecords.minnow.size,30);
assert.equal(legacy.nutravaganza.trophyRecords.minnow.catches,1);
F.ensure(legacy,day);
assert.equal(legacy.nutravaganza.trophyRecords.minnow.catches,1,'Old save migration is idempotent');
const game=fs.readFileSync(path.join(__dirname,'../web/game.js'),'utf8');
const style=fs.readFileSync(path.join(__dirname,'../web/fishing.css'),'utf8');
assert.ok(game.includes('NutFishingUI.trophyHall(saved)'),'Record hall must be an actual navigable page');
assert.ok(game.includes('NutFishingUI?.trophyPreview?.(saved)'),'Estate must show trophy mounts');
assert.ok(style.includes('.fish-trophy-mount')&&style.includes('.fish-trophy-wall'),'Wooden mounts must have styling');
console.log('PASS 80 species bounds, incremental bests, keep/sell/release, large fish, migration and estate records');
