'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.join(__dirname,'..');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const update=read('web/update.js');
const invite=read('web/invite.js');
const game=read('web/game.js');
const index=read('web/index.html');
const main=read('android/app/src/main/java/io/github/mrcalzon02/nutbuster/MainActivity.java');
const manifest=read('android/app/src/main/AndroidManifest.xml');
const statusEl={textContent:''};
const doc={querySelector:selector=>selector==='[data-update-status]'?statusEl:null};
let shares=0,releaseViews=0;
const android={
 NUTBUSTER_UPDATE_BRIDGE:{openReleases:()=>releaseViews++},
 NUTBUSTER_SHARE_BRIDGE:{shareInvite:()=>shares++}
};
vm.runInNewContext(update,{window:android,document:doc});
assert.equal(releaseViews,0,'no automatic release checks or browser activity at startup');
assert.equal(typeof android.NutbusterUpdates.autoCheck,'undefined','no background update API');
android.NutbusterUpdates.check();
assert.equal(releaseViews,1,'the update button launches the external release page');
android.NutbusterUpdates.openReleases();
assert.equal(releaseViews,2,'explicit release browser action works');
assert.match(statusEl.textContent,/Opening GitHub Releases/);
android.NutbusterUpdates.receive('Manual APK update');
assert.equal(statusEl.textContent,'Manual APK update');
vm.runInNewContext(invite,{window:android,document:doc});
const publicUrl='https://github.com/mrcalzon02/NUTBUSTER-R/releases';
assert.equal(android.NutbusterInvite.url,publicUrl);
const nativeInvite=android.NutbusterInvite.share();
assert.equal(shares,1);
let opened='',web={open:url=>{opened=url},prompt:()=>{}};
vm.runInNewContext(update,{window:web,document:doc});
assert.equal(opened,'','no web-side automatic check/download on startup');
web.NutbusterUpdates.check();
assert.equal(opened,publicUrl,'manual button links to all releases, including prereleases');
let copied='',posted=null;
const browser={navigator:{clipboard:{writeText:async t=>copied=t},share:async x=>posted=x}};
vm.runInNewContext(invite,{window:browser,document:doc});
const shareResult=browser.NutbusterInvite.share();
const copyResult=browser.NutbusterInvite.copy();
assert.match(main,/Intent\.ACTION_SEND/);
assert.match(main,/NUTBUSTER_SHARE_BRIDGE/);
assert.match(main,/NUTBUSTER_UPDATE_BRIDGE/);
assert.match(main,/openReleases\(\)/);
assert.doesNotMatch(main,/checkForUpdates|NutUpdateService|REQUEST_INSTALL_PACKAGES/);
assert.doesNotMatch(manifest,/REQUEST_INSTALL_PACKAGES|INTERNET|FileProvider/);
assert.match(manifest,/android:allowBackup="false"/);
assert.match(main,/s\.setBlockNetworkLoads\(true\)/);
assert.ok(index.indexOf('invite.js')<index.indexOf('game.js'));
assert.ok(index.indexOf('game.js')<index.indexOf('update.js'));
assert.match(game,/data-action="check-updates"/);
assert.doesNotMatch(game,/data-action="open-releases"/);
assert.doesNotMatch(game,/autoCheck/);
assert.match(game,/data-action="invite"/);
Promise.all([nativeInvite,shareResult,copyResult]).then(([nativeStatus,browserStatus,copyStatus])=>{
 assert.equal(nativeStatus,'native');
 assert.equal(browserStatus,'shared');
 assert.equal(posted.url,publicUrl);
 assert.equal(copyStatus,true);
 assert.equal(copied,publicUrl);
 console.log('PASS: manual GitHub release linking, no auto-download/install, native/web sharing and local-only saves.');
}).catch(error=>{console.error(error);process.exitCode=1});
