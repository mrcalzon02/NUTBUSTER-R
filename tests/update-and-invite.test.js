const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.join(__dirname,'..');
const read=name=>fs.readFileSync(path.join(root,name),'utf8');
const update=read('web/update.js');
const invite=read('web/invite.js');
const game=read('web/game.js');
const index=read('web/index.html');
const native=read('android/app/src/main/java/io/github/mrcalzon02/nutbuster/NutUpdateService.java');
const main=read('android/app/src/main/java/io/github/mrcalzon02/nutbuster/MainActivity.java');
const manifest=read('android/app/src/main/AndroidManifest.xml');
const statusEl={textContent:''};
const doc={querySelector:selector=>selector==='[data-update-status]'?statusEl:null};
let automatic=0,manual=0,shares=0;
let android={
 NUTBUSTER_UPDATE_BRIDGE:{checkForUpdatesAutomatically:()=>automatic++,checkForUpdates:()=>manual++},
 NUTBUSTER_SHARE_BRIDGE:{shareInvite:()=>shares++}
};
vm.runInNewContext(update,{window:android,document:doc});
assert.equal(automatic,1,'Boot probes once');
android.NutbusterUpdates.autoCheck('level');
assert.equal(automatic,2,'Level-start can request a throttled check');
android.NutbusterUpdates.check();
assert.equal(manual,1,'Explicit manual check works');
android.NutbusterUpdates.receive('Signed release found');
assert.equal(statusEl.textContent,'Signed release found');
vm.runInNewContext(invite,{window:android,document:doc});
const publicUrl='https://github.com/mrcalzon02/NUTBUSTER-R/releases';
assert.equal(android.NutbusterInvite.url,publicUrl);
const androidInvite=android.NutbusterInvite.share();
assert.equal(shares,1,'Native sharesheet is invoked without account access');
let opened='',web={open:url=>{opened=url},prompt:()=>{}};
vm.runInNewContext(update,{window:web,document:doc});
assert.equal(opened,'','Web fallback never opens network or downloads on boot');
web.NutbusterUpdates.autoCheck('level');assert.equal(opened,'','No automatic unauthenticated browser download');
web.NutbusterUpdates.check();assert.equal(opened,publicUrl,'Manual browser button links to releases');
let copied='',posted=null;
const browser={navigator:{clipboard:{writeText:async t=>copied=t},share:async x=>posted=x}};
vm.runInNewContext(invite,{window:browser,document:doc});
assert.equal(browser.NutbusterInvite.message.includes(publicUrl),true);
const shareResult=browser.NutbusterInvite.share();
const copyResult=browser.NutbusterInvite.copy();
assert.equal(main.includes('Intent.ACTION_SEND'),true);
assert.equal(main.includes('NUTBUSTER_SHARE_BRIDGE'),true);
assert.equal(main.includes('checkForUpdatesAutomatically()'),true);
assert.equal(main.includes('NUTBUSTER_UPDATE_BRIDGE'),true);
assert.match(manifest,/android:allowBackup="false"/);
assert.ok(!/READ_CONTACTS|GET_ACCOUNTS|ACCESS_FINE_LOCATION/.test(manifest));
assert.ok(index.indexOf('invite.js')<index.indexOf('game.js'));
assert.ok(index.indexOf('game.js')<index.indexOf('update.js'));
assert.match(game,/data-action="check-updates"/);
assert.match(game,/data-action="invite"/);
assert.match(game,/autoCheck\?\.\('level'\)/);
assert.match(native,/AUTO_CHECK_INTERVAL_MS/);
assert.match(native,/new AlertDialog\.Builder\(activity\)/);
assert.match(native,/\.setPositiveButton\("Download",/);
assert.match(native,/\.setPositiveButton\("Install",/);
assert.match(native,/lastOfferedCode/);
assert.match(native,/!signer\.equals\(fingerprint\(candidate\)\)/);
const discovery=native.slice(native.indexOf('private void runCheck('),native.indexOf('private void showDownloadOffer('));
assert.ok(discovery.includes('showDownloadOffer('));
assert.ok(!discovery.includes('downloadAndVerify('),'A version check must never download the APK');
Promise.all([androidInvite,shareResult,copyResult]).then(([nativeStatus,browserStatus,copyStatus])=>{
 assert.equal(nativeStatus,'native');
 assert.equal(browserStatus,'shared');
 assert.equal(posted.url,publicUrl);
 assert.equal(copyStatus,true);
 assert.equal(copied,publicUrl);
 console.log('PASS: native startup/level/manual checks, two-stage consent boundaries, native/web sharing, local-only saves.');
}).catch(error=>{console.error(error);process.exitCode=1});
