const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const A=require('../web/avatar-art.js');
const base=path.join(__dirname,'../web');
const html=fs.readFileSync(path.join(base,'index.html'),'utf8');
assert.ok(html.includes('<script src="avatar-art.js"></script>'),'Atlas must load in HTML');
assert.ok(html.indexOf('avatar-art.js')<html.indexOf('game.js'),'Avatar atlas must load before game');
assert.equal(A.COSTUMES.length,60);
assert.equal(A.TIERS.length,40);
assert.equal(A.SEASONAL.length,20);
assert.equal(new Set(A.COSTUMES.map(c=>c.id)).size,60,'No duplicate costume IDs');
const save={stars:{25:2},homestead:{avatar:'champion',purchases:{'royal-estate':true}}};
A.ensure(save);
assert.equal(save.homestead.outfit,'tier-03','Previously earned legacy champion maps to matching human sprite');
assert.equal(save.homestead.avatar,'champion','Legacy prestige title not removed');
assert.equal(A.equip(save,'tier-40'),false);
assert.equal(A.equip(save,'spring-blossom'),false);
assert.equal(A.equip(save,'constructor'),false,'No prototype injection');
assert.equal(A.current(save).id,'tier-03');
save.stars[5]=1;assert.equal(A.equip(save,'spring-blossom'),true);
assert.equal(A.current(save).category,'seasonal');
assert.equal(A.summary(save).seasonal,2,'Existing level-25 and newly won level-5 costumes are both owned');
const original=JSON.stringify(save);
A.ensure(save);
assert.equal(JSON.stringify(save),original,'Repeated migration is non-destructive');
save.stars[5]=0;
A.ensure(save);
assert.equal(save.homestead.outfit,'tier-03','Invalid entitlement falls back to valid legacy choice');
const fresh={stars:{},homestead:{avatar:'royal',purchases:{'royal-estate':true}}};
A.ensure(fresh);
assert.equal(fresh.homestead.outfit,'tier-01','Royal legacy premium does not falsify campaign completion');
assert.equal(A.owned(fresh,'tier-02'),false,'Unplayed campaign markers cannot grant avatar skins');
fresh.unlocked=500;
assert.equal(A.owned(fresh,'tier-40'),false,'Unlocked map is not proof of victory');
fresh.stars[500]=3;assert.equal(A.owned(fresh,'tier-40'),true);
assert.equal(A.unlockedAt(500).some(c=>c.id==='tier-40'),true);
for(const c of A.COSTUMES.filter(c=>c.category==='seasonal')){
 assert.ok(Number.isInteger(c.level)&&c.level>=1&&c.level<=500);
 fresh.stars[c.level]=1;
 assert.equal(A.owned(fresh,c.id),true,'Seasonal archive does not depend on calendar date');
}
assert.equal(A.summary(fresh).seasonal,20);
console.log('PASS: avatar entitlements, reward unlocks, save migration and seasonal progression');
