// Regression: do not replace the author's atlas art with huge currency pills or SVG powerups.
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.join(__dirname,'..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const index=read('web/index.html'),css=read('web/style.css'),source=read('web/game.js');
const header=index.match(/<header class="top">[\s\S]*?<\/header>/)?.[0];
const footer=index.match(/<nav class="bottom"[\s\S]*?<\/nav>/)?.[0];
assert.ok(header&&footer);
assert.doesNotMatch(header,/<svg\b|<strong>|THE ULTIMATE PREMIUM NUT EXPERIENCE/);
assert.equal((header.match(/<img class="currency-icon"/g)||[]).length,2);
assert.match(header,/art\/primary\/economy\/golden-nuts.png/);
assert.match(header,/art\/additions\/economy\/prismatic-acorn.png/);
assert.equal((footer.match(/<img class="nav-icon"/g)||[]).length,5,'all nav icons are original art');
assert.doesNotMatch(footer,/<svg\b/,'no replacement SVG navigation');
assert.match(css,/#app\.playing \.top\{display:none\}/,'banner must disappear during play');
assert.match(css,/\.money button\{[^}]*background:transparent;border:0/,'currency displays must have no giant pills');
assert.match(css,/\.play-wallet button\{[^}]*background:none/,'play currency buttons use tiny unboxed controls');
assert.doesNotMatch(source,/BOOSTER_ICON_PATHS|return '<svg class="booster-icon"/,'no hand-drawn substitute symbols');
const art=source.match(/const BOOSTER_ART=Object\.freeze\(\{([\s\S]*?)\}\)/)?.[1];
assert.ok(art,'booster art mapping missing');
const paths=[...art.matchAll(/^\s*(\w+):'([^']+)'/gm)];
assert.equal(paths.length,10,'ten tactical boosters have authored sprite maps');
for(const [,id,src] of paths)assert.ok(fs.existsSync(path.join(root,'web',src)),id+' missing original art: '+src);
assert.match(css,/#app\.playing \.game-active \.boosters \.booster-icon\{[^}]*object-fit:contain/);
const E=require('../web/engine.js'),P=require('../web/progression.js');
const H=require('../web/homestead.js'),A=require('../web/avatar-art.js');
const M=require('../web/campaign-maps.js'),F=require('../web/board-features.js');
let html='',playing=false;
const screen={classList:{toggle(){}},addEventListener(){},get innerHTML(){return html;},set innerHTML(v){html=v;},querySelector(){return null},querySelectorAll(){return []}};
const wallet={textContent:''},gems={textContent:''},toast={textContent:'',classList:{add(){},remove(){}}};
const document={getElementById:id=>({screen,wallet,gems,toast,app:{classList:{toggle(n,v){if(n==='playing')playing=v;}}}}[id]||null),querySelectorAll(){return []},querySelector(){return null}};
const window={NutDailyMoves:require('../web/daily-moves.js'),NutElementalChallenges:require('../web/elemental-challenges.js'),NutElementalRewards:require('../web/elemental-rewards.js'),NutEngine:E,NutProgress:P,NutHomestead:H,NutAvatarArt:A,NutCampaignMaps:M,NutBoardFeatures:F,addEventListener(){}};
vm.runInNewContext(source,{window,document,localStorage:{getItem(){return null},setItem(){}},setTimeout(){},clearTimeout(){},console});
window.NutbusterApp.start(12);
assert.ok(playing);
assert.equal((html.match(/<img class="booster-icon"/g)||[]).length,10);
assert.doesNotMatch(html,/<svg class="booster-icon"/);
assert.equal((html.match(/<img class="hold-icon"/g)||[]).length,2,'New hold powers use existing original illustrations');
assert.equal((html.match(/class="play-wallet"/g)||[]).length,1);
assert.match(html,/id="play-wallet">250</);
assert.match(html,/id="play-gems">25</);
window.NutbusterApp.start(500);
assert.equal((html.match(/<img class="booster-icon"/g)||[]).length,10);
console.log('PASS: no SVG currency/booster/nav substitutions, 12 existing artwork paths, minimized play header, 10 illustrated boosts and compact in-play balances');
